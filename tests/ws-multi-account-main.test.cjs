'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const mainPath = path.join(__dirname, '..', 'resources', 'app', 'main.cjs');
const preloadPath = path.join(__dirname, '..', 'resources', 'app', 'preload.cjs');
const main = fs.readFileSync(mainPath, 'utf8');
const preload = fs.readFileSync(preloadPath, 'utf8');

assert.match(main, /wsViews\s*=\s*new Map\(\)/, 'main process keeps an account keyed BrowserView registry');
assert.match(main, /activeWsAccountId/, 'main process tracks active account id');
assert.match(main, /A-Za-z0-9._:-/, 'account ids accept colon as allowed by the account API');
assert.match(main, /wsViews\.delete\(id\)/, 'destroying a view removes its registry record');
assert.match(main, /sessionHardened:\s*false/, 'recreated views start with fresh session hardening');
assert.match(main, /if \(id === activeWsAccountId\) \{ wsViewState/, 'inactive account status cannot overwrite active state');
assert.match(preload, /accountId.*wsActiveAccountId|wsActiveAccountId.*accountId/, 'preload filters status events to the active account');
assert.match(preload, /previousWsAccountId|previous.*wsActiveAccountId/, 'failed account switches retain the previous active account');
assert.match(preload, /invoke\('zhike-ws',[\s\S]*?then\(/, 'active account commits only after IPC succeeds');
assert.match(main, /restoreWsAccount|previousActiveWsAccountId/, 'failed BrowserView loads restore main active account');
assert.match(main, /reloadContext/, 'reload failures keep a per-view rollback context');
assert.match(main, /did-fail-load[\s\S]*?restoreWsAccount/, 'did-fail-load restores the previous active view');
assert.match(main, /catch \(error\).*restoreWsAccount|restoreWsAccount\([\s\S]*?throw error/, 'load failures roll back BrowserView switching');
assert.match(main, /persist:ws-workbench-/, 'views use account-isolated persistent partitions');
assert.match(main, /accountId/, 'WS IPC accepts account ids');
assert.match(main, /\[['"]list['"],\s*['"]create['"]\]\.includes\(action\)|action\s*===\s*['"]create['"][\s\S]{0,180}\/api\/ws\/accounts/, 'account creation uses the collection endpoint instead of a trailing slash item endpoint');
assert.match(main, /addBrowserView|setBrowserView/, 'views attach to the main window');
assert.match(main, /removeBrowserView/, 'switching or clearing removes only the selected view');
assert.match(main, /setBounds\(\{ x: 0, y: 0, width: 0, height: 0 \}\)/, 'inactive views are hidden without destroying them');
assert.match(main, /getContentBounds/, 'bounds are clamped to window content');
assert.match(main, /toolbarHeight\s*=\s*96/, 'view bounds stay below the compact workbench toolbar');
assert.match(main, /function sameWsBounds\(previous,\s*next\)[\s\S]*?previous\.x === next\.x[\s\S]*?previous\.height === next\.height/, 'main process has a geometry equality guard for BrowserView bounds');
assert.match(main, /if \(sameWsBounds\(record\.lastBounds,\s*next\)\)[\s\S]*?return true;/, 'identical BrowserView bounds skip native setBounds');
assert.match(main, /function hideWsView\(record\)[\s\S]*?record\.lastBounds\s*=\s*\{\s*hidden:\s*true\s*\}/, 'hiding a BrowserView invalidates the cached visible bounds');
assert.match(main, /zhike-ws-status[^\n]*accountId|accountId[^\n]*zhike-ws-status/, 'status events include the account id');
assert.match(main, /persistWsAccountStatus/, 'runtime WS status is persisted to the account row');
assert.match(main, /method:\s*'PATCH'[\s\S]*api\/ws\/accounts\//, 'status persistence uses the account-scoped PATCH endpoint');
assert.match(main, /wsStatusPersistence\s*=\s*new Map\(\)/, 'status persistence coalesces rapid transitions per account');
assert.match(main, /action === ['"]clear-session['"][\s\S]*?accountId/, 'clear-session is account scoped');
assert.match(main, /action === ['"]open['"][\s\S]*?default/, 'legacy open action still defaults to default account');
assert.match(preload, /accountId/, 'desktop preload forwards account context');
assert.match(preload, /onWsStatus/, 'desktop preload keeps status listener');
assert.doesNotMatch(main, /session\.cookies|document\.cookie/, 'main source does not expose session secrets');
console.log('ws-multi-account-main: expected registry, isolation, switching, bounds and legacy IPC contracts');
