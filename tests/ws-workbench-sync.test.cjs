'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const repo = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(repo, relative), 'utf8');
const ui = read('resources/app/modules/ws-workbench.js');
const server = read('resources/app/server.mjs');
const core = require(path.join(repo, 'resources/app/modules/ws-workbench-core.js'));
const crm = require(path.join(repo, 'resources/app/modules/ws-crm-sync-core.js'));
assert.deepEqual(core.dedupeMessages([{ externalId: 'a', order: 2 }, { externalId: 'b', order: 1 }, { externalId: 'a', order: 3 }]).map(row => row.externalId), ['b', 'a']);
const customer = { id: 'c1', tags: ['old'], wsAccountIds: ['one'] };
core.mergeCustomerProfile(customer, { wsAccountId: 'two', wsExternalId: 'x', conversationId: 'conv', tags: ['new'] });
assert.deepEqual(customer.wsAccountIds, ['one', 'two']);
assert.deepEqual(customer.tags, ['old', 'new']);
assert.equal(crm.deriveCustomerProfile({ contact: { name: '客户', phone: '+91 99999 11111' } }, { externalId: 'x', title: '客户' }, 'two').wsExternalId, 'x');
assert.match(ui, /syncConversationListPreviews/);
assert.match(ui, /discover-conversations/);
assert.match(ui, /列表发现/, 'discovery counts remain readable for both stored and active collection');
assert.match(ui, /COLLECTION_CAPABILITY_BLOCKED/, 'unavailable legacy collection must be explicit');
assert.match(ui, /maybeStartAutomaticReadHistoryCollection/);
assert.match(ui, /readHistoryAutoStarted/);
assert.match(ui, /analyzeStoredConversation/);
assert.match(ui, /unreadCount\)\s*>\s*0|unreadCount\s*\|\|\s*conversation\.unread|skipped_unread/, 'AI 恢复队列必须继续跳过未读会话');
assert.match(ui, /analysisStatus/);
assert.match(ui, /coverageStatus:\s*unreadConversation\s*\?\s*'unread-skipped'\s*:\s*'list-only'/, '列表无预览时仍需标记采集完成');
assert.match(ui, /progressed/, '列表采集进度需要在无预览行时继续推进');
assert.match(ui, /if \(!state\.backgroundActive \|\| !collectionReady\('backgroundCollection'\)\) return;/,
  'the shared session lifetime cannot poll before the independent collector is running');
assert.match(ui, /async function refreshCollectionSummary\(options = \{\}\) \{\s*if \(!collectionReady\('backgroundCollection'\)\) return collectionBlockedResult\(\);/,
  'automatic refresh must stop before queue reads/writes when independent login is not ready');
assert.match(ui, /syncAnalysisToCrm/);
assert.match(ui, /phone:\s*core\.extractPhone\(`\$\{externalId\} \$\{title\}`\)/, 'automatic identity matching may only inspect conversation identity fields');
assert.doesNotMatch(ui, /phone:\s*core\.extractPhone\(`\$\{externalId\} \$\{title\} \$\{preview\}`\)/, 'message previews must not supply customer identity phone numbers');
assert.doesNotMatch(ui, /低置信度或缺少分析编号，等待人工确认/);
assert.match(ui, /低置信度.*只补空字段/);
assert.match(ui, /保留原值/);
assert.match(ui, /getStateVersion/);
assert.match(server, /\/api\/ws\/crm-sync/);
assert.match(server, /未匹配到现有客户档案.*不会新增客户/);
assert.match(server, /matched:\s*true/);
assert.match(server, /followupAlerts/);
assert.match(server, /INSERT INTO ws_messages/);
assert.match(server, /stateVersionFailure/);
assert.match(server, /refreshWsCollectionRunCounters/);
assert.match(server, /const softDeleted = false;/, 'WS analysis supplements existing customers but cannot auto-delete them');
console.log('ws-workbench-sync: idempotent messages, account linkage, AI CRM sync and follow-up contracts pass');
