'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const repo = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(repo, relative), 'utf8');
const readme = read('README.md');
const csproj = read('desktop/src/Zhike.Desktop/Zhike.Desktop.csproj');
const setup = read('zhike-desktop-setup.iss');
const bundle = read('scripts/build-winui-bundle.ps1');
const installer = read('scripts/build-winui-installer.ps1');
const packageJson = JSON.parse(read('resources/app/package.json'));
const expected = packageJson.version;
const displayVersion = expected.split('.').slice(0, 2).join('.');
const releaseNotes = read(`docs/release/release-notes-${expected}.md`);
const operationsUpgrade = read('resources/app/modules/operations-upgrade.js');
const indexHtml = read('resources/app/index.html');
const server = read('resources/app/server.mjs');
const app = read('resources/app/app.js');
const gptAssistant = read('resources/app/modules/gpt-assistant.js');
const dataCenter = read('resources/app/modules/v4-data-center.js');

assert.match(expected, /^\d+\.\d+\.\d+$/);
assert.ok(readme.startsWith(`# 知客 ${displayVersion} A+B 本机桌面版`));
for (const tag of ['Version', 'InformationalVersion']) assert.ok(csproj.includes(`<${tag}>${expected}</${tag}>`));
for (const tag of ['AssemblyVersion', 'FileVersion']) assert.ok(csproj.includes(`<${tag}>${expected}.0</${tag}>`));
assert.ok(setup.includes(`#define AppVersion "${expected}"`));
assert.equal(setup.match(/^MinVersion=(.+)$/m)?.[1], csproj.match(/-windows(\d+\.\d+\.\d+)\.0</)?.[1]);
assert.ok(setup.includes(`zhike-winui-${expected}-win-x64`));
assert.match(setup, /OutputBaseFilename=知客-\{#AppVersion\}-WinUI桌面版/);
assert.equal(bundle.match(/\[string\]\$Version\s*=\s*'([^']+)'/)?.[1], expected);
assert.equal(installer.match(/\[string\]\$AppVersion\s*=\s*'([^']+)'/)?.[1], expected);
assert.equal(packageJson.zhikeRuntime.host, 'WinUI 3 + WebView2');
assert.equal(packageJson.zhikeRuntime.storage, 'SQLite');
assert.doesNotMatch(JSON.stringify(packageJson), /electron|docker|postgres/i);
assert.ok(releaseNotes.startsWith(`# 知客 ${expected} A+B 预发行说明`));
assert.match(releaseNotes, /已知限制|实机验收|WhatsApp/);
assert.doesNotMatch(releaseNotes, /docker compose|PostgreSQL.*服务端|双存储模式/i);
assert.ok(operationsUpgrade.includes(`runtimeVersion:'${expected}'`));
assert.ok(app.includes(`productVersion:'${expected}'`));
assert.ok(indexHtml.includes(`<title>知客 ${displayVersion} · Horizon Atelier</title>`));
assert.ok(indexHtml.includes(`<strong>知客 ${displayVersion}</strong>`));
assert.equal(server.match(/const APP_VERSION = '([^']+)'/)?.[1], expected);
const readinessProject = read('scripts/stage51/NativeReadinessProbe/NativeReadinessProbe.csproj');
const nativeWindow = read('desktop/src/Zhike.Desktop/MainWindow.xaml.cs');
const desktopTools = read('desktop/src/Zhike.Desktop/Services/DesktopToolsService.cs');
const localService = read('desktop/src/Zhike.Desktop/Services/LocalServiceManager.cs');
assert.ok(readinessProject.includes(`<Version>${expected}</Version>`));
assert.ok(nativeWindow.includes(`知客 ${expected}  Horizon Atelier`));
for (const field of ['appVersion', 'productVersion']) assert.ok(desktopTools.includes(`state["${field}"] = "${expected}";`));
assert.ok(localService.includes(`?? "${expected}"`));
assert.doesNotMatch(indexHtml, /<title>知客 5\./, '正式文档标题不能回滚到 5.x');
assert.doesNotMatch(gptAssistant, /知客 GPT <em>4\.1<\/em>/, 'GPT 工作区不能显示旧版产品号');
assert.doesNotMatch(dataCenter, /4\.1 (?:数据库健康与诊断|多维转化中心)/, '数据中心和统计页不能显示旧版产品号');
assert.doesNotMatch(app, /(?:撤销 )?4\.1 批量运营写入前快照/, '6.0 操作记录不能继续生成旧版快照名称');

console.log(`release consistency: WinUI + SQLite ${expected} candidate metadata agrees across current entry points`);
