'use strict';
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const repo = path.resolve(__dirname, '..', '..');
const script = path.join(__dirname, 'audit-queue-mapping.cjs');
const result = spawnSync(process.execPath, [script, '--read-only'], { cwd: repo, encoding: 'utf8' });
assert.equal(result.status, 0, result.stderr || result.stdout);
const report = JSON.parse(result.stdout);
assert.equal(report.readOnly, true);
assert.equal(report.migrationRunner.maxInlineVersion, 0);
assert.equal(report.migrationRunner.manifestMax, Math.max(...report.migrationRunner.migrationVersions));
assert.ok(report.migrationRunner.manifestMax >= 22);
assert.ok(report.tables.includes('ws_collection_runs'));
assert.ok(report.tables.includes('ws_collection_items'));
assert.ok(report.tables.includes('ai_jobs'));
assert.ok(report.writers.some(item => item.includes('ws-workbench.js')));
assert.ok(!report.blockers.some(item => item.includes('inline schema version checks')));
console.log('stage0 queue audit contract: read-only schema and writer findings pass');
