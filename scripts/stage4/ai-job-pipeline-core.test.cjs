'use strict';
const assert = require('node:assert/strict');
const core = require('../../resources/app/modules/ai-job-pipeline-core.js');

assert.deepEqual(core.status('retryable'), 'retry_scheduled');
assert.equal(core.legacyStatus('retry_scheduled'), 'retryable');
assert.ok(core.canTransition('queued', 'running'));
assert.ok(!core.canTransition('completed', 'running'));
const queued = core.normalizeJob({ id: 'j1', accountId: 'a', conversationId: 'c', status: 'queued', idempotencyKey: 'k', checkpoint: { completedChunks: 0, chunkCount: 3 } });
const claim = core.claim(queued, 'worker-a');
assert.equal(claim.claimed, true);
assert.equal(claim.job.status, 'running');
assert.equal(claim.job.attempts, 1);
assert.equal(claim.job.workerOwnerId, 'worker-a');
assert.throws(() => core.advanceCheckpoint(claim.job.checkpoint, { completedChunks: 0, chunkCount: 3 }), /单调/);
const checkpoint = core.advanceCheckpoint(claim.job.checkpoint, { completedChunks: 1, chunkCount: 3, cursor: 'm1' });
assert.equal(checkpoint.completedChunks, 1);
const cancelled = core.cancel(claim.job, 'operator');
assert.equal(cancelled.job.status, 'cancelled');
assert.equal(cancelled.job.cancelRequested, true);
assert.throws(() => core.transition(cancelled.job, 'completed'), /非法|取消/);
const retried = core.scheduleRetry({ ...claim.job, status: 'running', attempts: 1 }, 'timeout', Date.parse('2026-01-01T00:00:00Z'));
assert.equal(retried.job.status, 'retry_scheduled');
assert.ok(retried.job.nextAttemptAt);
const maxed = core.scheduleRetry({ ...claim.job, status: 'running', attempts: 5, maxAttempts: 5 }, 'fatal');
assert.equal(maxed.retry, false);
assert.equal(maxed.job.status, 'failed');
assert.equal(core.makeIdempotencyKey({ accountId: 'a', conversationId: 'c' }), 'a:ws.ai.analysis:c');
assert.throws(() => core.validateResult({ evidence: [{ field: 'age' }] }), /证据/);
assert.doesNotThrow(() => core.validateResult({ profileFacts: { age: { value: 36, evidence: '我36岁' } }, evidence: [{ field: 'age', value: 36, text: '我36岁' }] }));
console.log('ai job pipeline core: PASS');
