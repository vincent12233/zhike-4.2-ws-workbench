'use strict';
// Local sidecar registration/query diagnostic. Never starts WinUI, WebView or WhatsApp.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const { spawn, execFileSync } = require('node:child_process');
const { randomBytes, randomUUID, createHash } = require('node:crypto');
const { performance } = require('node:perf_hooks');
const { DatabaseSync } = require('node:sqlite');
const LEVELS = [1, 5, 10, 20, 30, 50];
const GROUPS_PER_ACCOUNT = 3;
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const round = n => Math.round(n * 1000) / 1000;
function summary(values) {
  const sorted = [...values].sort((a, b) => a - b);
  return { count: sorted.length, minMs: round(sorted[0]), medianMs: round(sorted[Math.floor(sorted.length / 2)]),
    p95Ms: round(sorted[Math.max(0, Math.ceil(sorted.length * 0.95) - 1)]), maxMs: round(sorted.at(-1)),
    meanMs: round(sorted.reduce((a, b) => a + b, 0) / sorted.length), samplesMs: values.map(round) };
}
async function measure(run, samples) {
  await run(); // One explicit warm-up, excluded from the samples.
  const times = [];
  for (let i = 0; i < samples; i++) { const at = performance.now(); await run(); times.push(performance.now() - at); }
  return summary(times);
}
function resourceSample(child) {
  if (process.platform !== 'win32') return { status: 'UNMEASURED', reason: 'Windows process counters are unavailable on this platform.' };
  if (!child || child.exitCode !== null || child.signalCode !== null) return { status: 'UNMEASURED', reason: 'Owned sidecar is no longer running.' };
  // IDs are generated by spawn, never accepted as command-line/user input.
  const pid = Number(child.pid), parentPid = Number(process.pid);
  if (!Number.isSafeInteger(pid) || pid <= 0) return { status: 'UNMEASURED', reason: 'Owned process ID was not available.' };
  const command = `$ErrorActionPreference='Stop'; $owned=Get-CimInstance Win32_Process -Filter 'ProcessId=${pid}'; if(!$owned -or $owned.ParentProcessId -ne ${parentPid}){throw 'Owned process identity changed'}; $p=Get-Process -Id ${pid}; $r=@{status='MEASURED';timestampUtc=[DateTime]::UtcNow.ToString('o');pid=$p.Id;totalCpuMs=$p.TotalProcessorTime.TotalMilliseconds;workingSetBytes=$p.WorkingSet64;peakWorkingSetBytes=$p.PeakWorkingSet64;privateMemoryBytes=$p.PrivateMemorySize64}; $all=@(Get-CimInstance Win32_Process | Select-Object ProcessId,ParentProcessId,Name); $seen=@(${pid}); $desc=@(); do { $next=@($all | Where-Object {$_.ParentProcessId -in $seen -and $_.ProcessId -notin $seen}); foreach($item in $next){$seen+=$item.ProcessId; $desc+=@{pid=$item.ProcessId;parentPid=$item.ParentProcessId;name=$item.Name}} } while($next.Count -gt 0); $r.descendants=$desc; $r.webViewDescendantCount=@($desc | Where-Object {$_.name -match '(?i)msedgewebview2|webview'}).Count; $r | ConvertTo-Json -Depth 5 -Compress`;
  try { return JSON.parse(execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', command], { encoding: 'utf8', windowsHide: true, timeout: 15000, stdio: ['ignore', 'pipe', 'pipe'] }).trim()); }
  catch (error) { return { status: 'UNMEASURED', reason: String(error.code || 'PROCESS_COUNTER_UNAVAILABLE') }; }
}
async function freePort() {
  const socket = net.createServer();
  await new Promise((resolve, reject) => { socket.once('error', reject); socket.listen(0, '127.0.0.1', resolve); });
  const port = socket.address().port;
  await new Promise(resolve => socket.close(resolve));
  return port;
}
async function main(argv = process.argv.slice(2)) {
  let output = '', samples = 7;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--help') { console.log('node scripts/diagnostics/ws-account-scale.cjs [--output <new-report.json>] [--samples 3..50]\nCreates and deletes a fresh synthetic database; runs only the local Node sidecar.'); return; }
    if (argv[i] === '--output' && argv[i + 1]) output = path.resolve(argv[++i]);
    else if (argv[i] === '--samples' && argv[i + 1]) samples = Number(argv[++i]);
    else throw new Error('Unknown or incomplete option: ' + argv[i]);
  }
  if (!Number.isInteger(samples) || samples < 3 || samples > 50) throw new Error('--samples must be an integer between 3 and 50.');
  const repo = path.resolve(__dirname, '../..'), app = path.join(repo, 'resources/app');
  const serverPath = path.join(app, 'server.mjs');
  if (!fs.existsSync(serverPath)) throw new Error('Bundled server.mjs was not found relative to this script.');
  output ||= path.join(repo, 'work', 'diagnostics', 'ws-account-scale-' + new Date().toISOString().replace(/[:.]/g, '-') + '-' + randomUUID().slice(0, 8) + '.json');
  if (fs.existsSync(output)) throw new Error('Output already exists; choose a new report path.');
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'zhike-account-scale-'));
  assert.ok(path.dirname(dataDir) === path.resolve(os.tmpdir()) && path.basename(dataDir).startsWith('zhike-account-scale-'));
  const report = {
    schema: 'zhike.ws.account-scale.diagnostic.v1', startedAt: new Date().toISOString(), status: 'RUNNING',
    source: { serverSha256: createHash('sha256').update(fs.readFileSync(serverPath)).digest('hex'), nodeVersion: process.version, nodeExecutable: process.execPath },
    environment: { platform: process.platform, arch: process.arch, osRelease: os.release(), logicalCpuCount: os.cpus().length, totalSystemMemoryBytes: os.totalmem() },
    scope: { levels: LEVELS, defaultOrdinaryAccountCount: 1, groupsPerDedicatedAccount: GROUPS_PER_ACCOUNT, samples,
      dataset: 'Synthetic registered accounts and disabled monitor-target directory rows only; no chat messages or real profiles.',
      startupDefinition: 'Spawn to first successful /api/health; initial fresh database separately, then populated database restart at each level.',
      queryDefinition: 'Warm queries only: one excluded warm-up, sequential samples. HTTP includes loopback/JSON; SQLite includes prepare/all on a separate read-only connection.',
      resourceDefinition: 'Optional Windows cumulative process CPU and memory; interval CPU is sampled across queries and process-counter collection, not a machine-wide load percentage.',
      notMeasured: ['Saved WhatsApp login validity', 'Live foreground online accounts', 'Native account-switch latency', 'Initialized foreground/background WebViews', 'Real collector throughput or concurrency', 'Real group operation latency', 'Windows/Android/iOS notifications'],
      webViewBoundary: 'No UI executable is launched. Descendant checks are point-in-time observations of this owned sidecar, not a global claim about user applications.' },
    syntheticDataRoot: dataDir, launches: [], levels: [], cleanup: {},
  };
  const secrets = new Set(); let service = null, db = null;
  const redact = value => { let text = String(value); for (const secret of secrets) text = text.split(secret).join('[REDACTED]'); return text; };
  async function start(label) {
    const port = await freePort(), apiToken = randomBytes(32).toString('hex'), shutdownToken = randomBytes(32).toString('hex');
    secrets.add(apiToken); secrets.add(shutdownToken);
    const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.toUpperCase().startsWith('ZHIKE_')));
    Object.assign(env, { ZHIKE_DATA_DIR: dataDir, ZHIKE_PORT: String(port), ZHIKE_API_TOKEN: apiToken,
      ZHIKE_SHUTDOWN_TOKEN: shutdownToken, ZHIKE_STORAGE_MODE: 'local', ZHIKE_PARENT_PID: String(process.pid), ZHIKE_NATIVE_WRITE_TOKEN: '' });
    const started = performance.now();
    const child = spawn(process.execPath, ['server.mjs'], { cwd: app, env, windowsHide: true, stdio: ['ignore', 'ignore', 'pipe'] });
    const launch = { label, pid: child.pid ?? null, startedAt: new Date().toISOString() };
    report.launches.push(launch);
    let stderr = '', spawnError = null;
    child.stderr.on('data', chunk => { stderr = (stderr + chunk.toString()).slice(-8192); });
    child.on('error', error => { spawnError = error; });
    const closed = new Promise(resolve => child.once('close', (code, signal) => { launch.exitCode = code; launch.exitSignal = signal; resolve(); }));
    const base = 'http://127.0.0.1:' + port;
    async function request(route, body, expected = 200, extraHeaders = {}) {
      const response = await fetch(base + route, { method: body === undefined ? 'GET' : 'POST',
        headers: { 'x-zhike-api-token': apiToken, origin: base, 'content-type': 'application/json', ...extraHeaders },
        body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(10000) });
      const payload = await response.json();
      assert.equal(response.status, expected, route + ': ' + JSON.stringify(payload));
      return payload;
    }
    service = { child, launch, closed, request, shutdownToken };
    let lastError;
    while (performance.now() - started < 20000) {
      if (spawnError || child.exitCode !== null || child.signalCode !== null) throw new Error('Sidecar startup failed: ' + (spawnError?.code || launch.exitCode) + ' ' + redact(stderr));
      try { const health = await request('/api/health'); launch.startupMs = round(performance.now() - started); launch.health = health; return; }
      catch (error) { lastError = error; await wait(50); }
    }
    throw new Error('Sidecar readiness timeout: ' + (lastError?.cause?.code || lastError?.code || lastError?.message) + ' ' + redact(stderr));
  }
  async function stop() {
    if (!service) return;
    const current = service; service = null;
    const started = performance.now(); let shutdownAccepted = false;
    try { await current.request('/api/shutdown', {}, 200, { 'x-zhike-shutdown-token': current.shutdownToken }); shutdownAccepted = true; }
    catch (error) { current.launch.shutdownError = redact(error.message); }
    let timer;
    await Promise.race([current.closed, new Promise(resolve => { timer = setTimeout(resolve, 5000); })]);
    clearTimeout(timer);
    const forced = current.child.exitCode === null && current.child.signalCode === null;
    if (forced) { current.child.kill(); await current.closed; }
    Object.assign(current.launch, { shutdownAccepted, forcedTermination: forced, shutdownMs: round(performance.now() - started),
      cleanExit: shutdownAccepted && !forced && current.launch.exitCode === 0,
      workspaceLockRemoved: !fs.existsSync(path.join(dataDir, '.workbench.lock')) });
    if (!current.launch.cleanExit || !current.launch.workspaceLockRemoved) throw new Error('Owned sidecar did not exit cleanly.');
  }
  try {
    await start('fresh-empty-database');
    report.initialStartupMs = service.launch.startupMs;
    let registered = 0;
    for (const level of LEVELS) {
      const seedAt = performance.now();
      while (registered < level) {
        const id = 'scale-dedicated-' + String(++registered).padStart(3, '0');
        await service.request('/api/ws/accounts', { id, displayName: 'Synthetic dedicated ' + registered, workspaceMode: 'dedicated', status: '未连接' }, 201);
        const { profile } = await service.request('/api/ws/group-monitors/profiles', { accountId: id, slotKey: 'scale-directory', enabled: false }, 201);
        await service.request('/api/ws/group-monitors/' + profile.id + '/targets/scan?accountId=' + id, { accountId: id,
          targets: Array.from({ length: GROUPS_PER_ACCOUNT }, (_, index) => ({ groupJid: id + '-' + (index + 1) + '@g.us', groupName: 'Synthetic directory ' + (index + 1), enabled: false })) });
      }
      const seedMs = round(performance.now() - seedAt);
      await stop();
      await start('dedicated-registered-' + level);
      db = new DatabaseSync(path.join(dataDir, 'workspace.sqlite'), { readOnly: true });
      const before = resourceSample(service.child);
      if (before.status === 'MEASURED') assert.equal(before.webViewDescendantCount, 0, 'Owned sidecar unexpectedly spawned a WebView.');
      const accounts = await service.request('/api/ws/accounts');
      assert.equal(accounts.accounts.filter(account => account.workspaceMode === 'dedicated').length, level);
      assert.equal(accounts.accounts.filter(account => account.workspaceMode === 'ordinary').length, 1);
      assert.ok(accounts.accounts.every(account => account.status !== '已连接'));
      const httpAccountDirectory = await measure(async () => { assert.equal((await service.request('/api/ws/accounts')).accounts.length, level + 1); }, samples);
      const sqliteAccountDirectory = await measure(() => { assert.equal(db.prepare("SELECT * FROM ws_accounts ORDER BY CASE WHEN id='default' THEN 0 ELSE 1 END, created_at ASC").all().length, level + 1); }, samples);
      const selectedAccounts = [];
      for (const id of [...new Set(['scale-dedicated-001', 'scale-dedicated-' + String(level).padStart(3, '0')])]) {
        const route = '/api/ws/accounts/' + id + '/groups?accountId=' + id + '&limit=1000';
        const httpGroupDirectory = await measure(async () => { const result = await service.request(route); assert.equal(result.accountId, id); assert.equal(result.groups.length, GROUPS_PER_ACCOUNT); assert.ok(result.groups.every(row => row.accountId === id && row.monitorTarget?.enabled === false)); }, samples);
        const sqliteGroupDirectory = await measure(() => { assert.equal(db.prepare('SELECT * FROM ws_group_catalog WHERE account_id=? ORDER BY last_seen_at DESC, group_name COLLATE NOCASE, group_jid LIMIT ?').all(id, 1000).length, GROUPS_PER_ACCOUNT); }, samples);
        const httpEmptyConversationQuery = await measure(async () => { assert.equal((await service.request('/api/ws/conversations?accountId=' + id + '&limit=50')).conversations.length, 0); }, samples);
        selectedAccounts.push({ accountId: id, syntheticGroupCount: GROUPS_PER_ACCOUNT, conversationCount: 0, httpGroupDirectory, sqliteGroupDirectory, httpEmptyConversationQuery });
      }
      const counts = Object.fromEntries(['ws_messages', 'ws_group_membership_events', 'ws_collection_runs', 'ai_jobs'].map(table => [table, db.prepare('SELECT COUNT(*) n FROM ' + table).get().n]));
      for (const [table, count] of Object.entries(counts)) assert.equal(count, 0, table + ' should remain empty.');
      assert.equal(db.prepare('SELECT COUNT(*) n FROM ws_group_monitor_profiles WHERE enabled<>0 OR last_heartbeat_at<>\'\'').get().n, 0);
      assert.equal(db.prepare('SELECT COUNT(*) n FROM ws_group_monitor_targets WHERE enabled<>0').get().n, 0);
      const after = resourceSample(service.child);
      if (after.status === 'MEASURED') assert.equal(after.webViewDescendantCount, 0, 'Owned sidecar unexpectedly spawned a WebView.');
      const resource = { before, after };
      if (before.status === 'MEASURED' && after.status === 'MEASURED') {
        resource.cpuTimeDeltaMs = round(after.totalCpuMs - before.totalCpuMs);
        resource.intervalWallMs = Date.parse(after.timestampUtc) - Date.parse(before.timestampUtc);
        resource.oneCoreAveragePercent = resource.intervalWallMs > 0 ? round(100 * resource.cpuTimeDeltaMs / resource.intervalWallMs) : null;
      }
      report.levels.push({ dedicatedRegisteredCount: level, defaultOrdinaryCount: 1, totalRegisteredCount: level + 1,
        newlySeededMs: seedMs, populatedStartupMs: service.launch.startupMs, httpAccountDirectory, sqliteAccountDirectory,
        selectedAccounts, noCollectionChecks: counts, resource });
      db.close(); db = null;
      console.log('Measured ' + level + ' dedicated registrations + 1 default ordinary account.');
    }
    await stop();
    report.status = 'PASS';
  } catch (error) { report.status = 'FAIL'; report.error = redact(error.stack || error.message); process.exitCode = 1; }
  finally {
    if (db) { db.close(); db = null; }
    if (service) try { await stop(); } catch (error) { report.status = 'FAIL'; report.cleanup.shutdownError = redact(error.message); process.exitCode = 1; }
    try { fs.rmSync(dataDir, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 }); report.cleanup.syntheticDataRemoved = !fs.existsSync(dataDir); }
    catch (error) { report.cleanup.syntheticDataRemoved = false; report.cleanup.error = String(error.code || error.message); report.status = 'FAIL'; process.exitCode = 1; }
    report.cleanup.allOwnedSidecarsExitedCleanly = report.launches.every(launch => launch.cleanExit === true);
    report.completedAt = new Date().toISOString();
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, JSON.stringify(report, null, 2) + '\n', { flag: 'wx' });
    console.log(report.status + ': ' + output);
  }
}
if (require.main === module) main().catch(error => { console.error(error.message); process.exitCode = 1; });
module.exports = { summary, LEVELS, GROUPS_PER_ACCOUNT };
